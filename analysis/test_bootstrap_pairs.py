"""Bootstrap contract tests; all inputs are fixed local fixtures or public data."""
from fractions import Fraction as F
import unittest

import bootstrap_pairs as boot
import bootstrap_tables


class BootstrapContract(unittest.TestCase):
    def test_display_preserves_a_ratio_interval_crossing_one(self):
        result = bootstrap_tables.interval({'point': 1.1049, 'percentile_95': [0.9995201753, 1.21881557]},
                                           digits=2, reference=1)
        self.assertEqual(result, '1.10 [0.9995, 1.2188]')

    def test_registered_index_stream_and_exact_percentiles(self):
        # Independently generated by the unchanged theory_bootstrap.py engine.
        import numpy as np
        counts, digest = boot.indices(4, 100, 20261010)
        self.assertEqual(digest, '2c5538f891e549d1c0d1e7efce1da65508e84e048109ad840d7f1e43706751bd')
        a = boot.Series(counts @ np.array([0, 1, 4, 3]), 4)
        b = boot.Series(counts @ np.array([1, 0, 1, 2]), 4)
        for series, point, interval in [(a, '2', ['1/2', '7/2']),
                                         (a - b, '1', ['-21/80', '181/80']),
                                         (a.ratio(b), '2', ['79/100', '37/10'])]:
            result = series.summary()
            self.assertEqual(result['point_exact'], point)
            self.assertEqual(result['percentile_95_exact'], interval)

    def test_one_undefined_draw_invalidates_interval(self):
        a = boot.Series([2, 3, 4, 5])
        b = boot.Series([1, 1, 0, 1])
        result = a.ratio(b).summary()
        self.assertEqual(result['undefined_draws'], 1)
        self.assertIsNone(result['percentile_95'])
        self.assertEqual(result['draws'], 3)

    def test_exact_tie_order_survives_float_collapse(self):
        a = 10**20
        result = boot.Series([a, a + 3, a + 1, a + 2], a).summary()
        self.assertEqual(result['percentile_95_exact'],
                         [str(F(a + 1, a) * F(19, 20) + F(a + 2, a) * F(1, 20)),
                          str(F(a + 2, a) * F(1, 20) + F(a + 3, a) * F(19, 20))])

    def test_extrema_and_gap_match_rational_evaluation(self):
        a = boot.Series([1, 2, 6], [3, 3, 5])
        b = boot.Series([1, 3, 7], [2, 4, 8])
        lower = a.extremum(b, True)
        upper = a.extremum(b, False)
        for i in range(3):
            self.assertEqual(lower.value(i), max(a.value(i), b.value(i)))
            self.assertEqual(upper.value(i), min(a.value(i), b.value(i)))
            self.assertEqual((upper - lower).value(i), min(a.value(i), b.value(i)) - max(a.value(i), b.value(i)))

    def test_pairing_uses_the_same_draw_for_identical_columns(self):
        import numpy as np
        counts, _ = boot.indices(5, 40)
        a = boot.Series(counts @ np.array([0, 1, 1, 0, 1]), 5)
        result = (a - a).summary()
        self.assertEqual(result['percentile_95_exact'], ['0', '0'])
        self.assertEqual(result['zero_draws'], 40)

    def test_truncation_bills_tokens_but_never_delivers(self):
        base = {'audit': True, 'weak4': True, 'truncated': True, 'has_code': True,
                'partitioned': True, 'input_tokens': 2, 'output_tokens': 7,
                'reasoning_tokens': 3, 'control_tokens': 1, 'final_tokens': 3,
                'task_id': 'x', 'candidate_id': 0}
        cell = {'missing': [], 'subset': 'main', 'k': 1, 'candidates': [base],
                'batches': [{'episodes': ['x'], 'barrier_s': '1.25'}]}
        result = boot.prompt_columns(cell, ['x'])
        self.assertEqual(result['refusal'], [1])
        self.assertEqual(result['delivered_output_tokens'], [0])
        self.assertEqual(result['reasoning_tokens_all'], [4])
        self.assertEqual(result['unselected_final_tokens'], [3])

    def test_missing_candidate_is_not_imputed(self):
        cell = {'missing': [], 'subset': 'main', 'k': 1, 'candidates': [],
                'batches': [{'episodes': ['x'], 'barrier_s': '1'}]}
        with self.assertRaisesRegex(ValueError, 'Incomplete candidate block'):
            boot.prompt_columns(cell, ['x'])


if __name__ == '__main__':
    unittest.main()
