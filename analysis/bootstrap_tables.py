"""Read-only validation and paper displays of paired prompt inference."""
from pathlib import Path
from hashlib import sha256
import json

ROOT = Path(__file__).resolve().parent


def load(evidence_dir=None):
    evidence_dir = ROOT / 'evidence' if evidence_dir is None else evidence_dir
    return json.loads((evidence_dir / 'bootstrap-results.json').read_text())


def validate(evidence_dir=None):
    evidence_dir = ROOT / 'evidence' if evidence_dir is None else evidence_dir
    result = load(evidence_dir)
    inputs = (evidence_dir / 'bootstrap-inputs.json').read_bytes()
    receipt = json.loads((evidence_dir / 'bootstrap-receipt.json').read_text())
    assert result['input_sha256'] == receipt['input_sha256'] == sha256(inputs).hexdigest()
    assert receipt['result_sha256'] == sha256((evidence_dir / 'bootstrap-results.json').read_bytes()).hexdigest()
    assert receipt['implementation_sha256'] == sha256((ROOT / 'bootstrap_pairs.py').read_bytes()).hexdigest()
    reference = json.loads((evidence_dir / 'bootstrap-reference-replay.json').read_text())
    assert reference['result_sha256'] == receipt['result_sha256']
    assert reference['reference_source_sha256'] == receipt['engine_sources']['registered_file_sha256']
    assert json.loads(inputs)['method_source_sha256'] == receipt['engine_sources']['current_engine_file_sha256']
    assert all(row['matches'] for row in reference['checks'])
    assert (result['draws'], result['seed'], result['n_prompts']) == (10000, 20261010, 106)
    assert result['resample_indices_sha256'] == '17c40c6a2d54ce2437b4c54fba1780814a6205d10c1fe46916b9100eed108ef5'
    assert [len(result[k]) for k in ('cells', 'paired_contrasts', 'financial', 'h2')] == [72, 78, 924, 18]
    assert all(r['replicate'] in (0, 1, 2) for r in result['cells'])
    assert all(r['cost_pause'] for r in result['cost_pause_audit'])
    assert result['analysis_role'] == 'conditional_diagnostics_outside_paused_registered_pipeline'
    assert result['registered_primary_inference_completed'] is False
    assert not result['experiments_run']
    fixed = [r for r in result['financial'] if r['policy'] != 'menu']
    return {'draws': result['draws'], 'seed_groups': 3, 'cells': 72,
            'fixed_configuration_financial_rows': len(fixed),
            'fixed_configuration_extended_rows': sum(r['extended_bound'] for r in fixed),
            'registered_primary_bootstrap': None,
            'analysis_role': 'conditional_diagnostics_outside_paused_registered_pipeline',
            'cost_pause_retained': True}


def fmt(value, digits=1):
    return ('%.*f' % (digits, value)).replace('-', '$-$')


def interval(metric, scale=1, digits=1, reference=None):
    if metric['percentile_95'] is None:
        return 'unidentified'
    endpoint_digits = digits
    if reference is not None and any(v * scale != reference and round(v * scale, digits) == reference
                                     for v in metric['percentile_95']):
        endpoint_digits = max(digits, 4)
    return '%s [%s, %s]' % (fmt(metric['point'] * scale, digits),
                           fmt(metric['percentile_95'][0] * scale, endpoint_digits),
                           fmt(metric['percentile_95'][1] * scale, endpoint_digits))


def numbers():
    r = load()
    serial = [x for x in r['paired_contrasts'] if x['contrast'] == 'budget' and x['config'] == 'serial']
    out = {'bootQualityTotal': str(len(serial)),
           'bootQualityPositive': str(sum(x['metrics']['q_correct']['percentile_95'][0] > 0 for x in serial)),
           'bootWrongPositive': str(sum(x['metrics']['q_wrong']['percentile_95'][0] > 0 for x in serial))}
    for basis, tag in [('window', 'Win'), ('generation_span', 'Span')]:
        x = next(x for x in r['h2'] if x['replicate'] == 1 and x['config'] == 'serial' and x['basis'] == basis)
        m = x['alpha_on_over_off']
        assert x['hardware_matched']
        out['bootHtwo' + tag] = fmt(m['point'], 2)
        out['bootHtwo' + tag + 'Lo'], out['bootHtwo' + tag + 'Hi'] = [fmt(v, 2) for v in m['percentile_95']]
    fixed = [x for x in r['financial'] if x['policy'] != 'menu']
    out['bootFinancialFixedRows'] = str(len(fixed))
    out['bootFinancialFixedExtendedRows'] = str(sum(x['extended_bound'] for x in fixed))
    out['bootFinancialMenuRows'] = str(len(r['financial']) - len(fixed))
    out['bootGapUpperMax'] = fmt(max(x['metrics']['admission_gap']['percentile_95'][1] for x in fixed), 2)
    assert all(x['metrics']['admission_gap']['positive_draws'] == 0 for x in fixed)
    return out


def render():
    r = load()
    header = '%% Paired prompt inference, results sha256=%s. Generated by bootstrap_tables.py.\n' % sha256((ROOT / 'evidence/bootstrap-results.json').read_bytes()).hexdigest()
    labels = {'coder-nonthinking': 'Coder', 'nemotron-thinking': 'Nemotron', 'q35-thinking': 'Qwen3.5 thinking',
              'q38-nonthinking': 'Qwen3.8 non-thinking', 'q38-thinking': 'Qwen3.8 thinking'}
    order = list(labels)
    lines = [header, r'\begin{table*}[t]',
             r'\caption{Initial evaluation-pipeline conditional paired changes from one to eight attempts under serial execution, reported separately for each generation seed. Entries are point estimates [2.5th, 97.5th bootstrap percentiles] from 10,000 draws of 106 paired prompt blocks. Quality changes are percentage points and bills are USD per 1,000 requests under the headline tariff. A dash denotes no archived tariff. Intervals are pointwise and conditional on the observed seed and schedule, computed outside the paused registered pipeline.}',
             r'\label{tab:bootstrap-budget}', r'\centering\small\setlength{\tabcolsep}{4pt}',
             r'\begin{tabular}{llrrrr}', r'\toprule',
             r'Stratum & Seed & $\Delta q^+$ (pp) & $\Delta q^-$ (pp) & $\Delta$ abstention (pp) & $\Delta B$ (USD/1,000) \\', r'\midrule']
    serial = sorted([x for x in r['paired_contrasts'] if x['contrast'] == 'budget' and x['config'] == 'serial'],
                    key=lambda x: (order.index(x['stratum']), x['replicate']))
    for x in serial:
        m = x['metrics']
        lines.append('%s & $r_%d$ & %s & %s & %s & %s \\\\' %
                     (labels[x['stratum']] if x['replicate'] == 0 else '', x['replicate'],
                      interval(m['q_correct'], 100), interval(m['q_wrong'], 100),
                      interval(m['refusal'], 100),
                      interval(m['bill_headline_usd'], 1000) if 'bill_headline_usd' in m else '--'))
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table*}']
    quality = '\n'.join(lines) + '\n'
    lines = [header, r'\begin{table*}[t]',
             r'\caption{Initial evaluation-pipeline Qwen3.8 thinking/non-thinking ratio of the cloud\textquotesingle s indifference share, at 2.4 USD per GPU hour and the headline tariff. Entries give point estimates and pointwise 95\% percentile intervals from 10,000 paired prompt draws outside the paused registered pipeline. They condition on the observed seed and schedule, holding costs fixed on the indicated window or generation-span basis. Matched means all four on/off and low/high cells ran on one GPU model. Extra decimals preserve endpoints close to one. $\dagger$: extended-bound thinking cell.}',
             r'\label{tab:bootstrap-h2}', r'\centering\small', r'\begin{tabular}{llcrr}',
             r'\toprule', r'Seed & Configuration & GPU matched & Window ratio & Generation-span ratio \\', r'\midrule']
    for rep in range(3):
        for config in ('serial', 'batch16', 'batch64'):
            w = next(x for x in r['h2'] if (x['replicate'], x['config'], x['basis']) == (rep, config, 'window'))
            s = next(x for x in r['h2'] if (x['replicate'], x['config'], x['basis']) == (rep, config, 'generation_span'))
            name = config + (r'$^\dagger$' if w['extended_bound'] else '')
            lines.append('$r_%d$ & %s & %s & %s & %s \\\\' %
                         (rep, name, 'yes' if w['hardware_matched'] else 'no',
                          interval(w['alpha_on_over_off'], digits=2, reference=1), interval(s['alpha_on_over_off'], digits=2, reference=1)))
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table*}']
    return {'bootstrap-budget.tex': quality, 'bootstrap-h2.tex': '\n'.join(lines) + '\n'}
